import fs from 'fs';
import path from 'path';

const manifestPath = path.resolve(process.cwd(), 'lib', 'clothing-designs', 'design-manifest.json');
const outputPath = path.resolve(
  process.cwd(),
  'Clothing-Mockup-Feature',
  'app',
  'src',
  'data',
  'clothingDesignsData.ts'
);

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

const categories = [
  { id: 'all', label: 'All Designs' },
  { id: 'anime', label: 'Anime & Manga' },
  { id: 'marvel', label: 'Marvel & Comics' },
  { id: 'automotive', label: 'Automotive & JDM' },
  { id: 'gaming', label: 'Gaming & Tech' },
  { id: 'streetwear', label: 'Streetwear & Urban' },
  { id: 'typography', label: 'Typography & Quotes' },
  { id: 'indian-cinema', label: 'Cinema & Stars' },
  { id: 'humor', label: 'Humor & Sarcasm' },
  { id: 'aesthetic', label: 'Aesthetic & Nature' },
];

const tsCode = `// Autogenerated from lib/clothing-designs/design-manifest.json
// Curated 96 Designs with Visual Classifications

export interface ClothingDesignArtwork {
  id: string;
  name: string;
  fileName: string;
  suggestedPlacement: string;
  colorHint: 'black' | 'white' | 'any';
  previewUrl: string;
  studioPreviewUrl: string;
}

export interface CuratedClothingDesign {
  id: string;
  folder: string;
  name: string;
  themeCategory: string;
  tags: string[];
  description?: string;
  artworks: ClothingDesignArtwork[];
  defaultArtworkId: string;
  previewUrl: string;
  studioPreviewUrl: string;
}

export const CLOTHING_DESIGN_CATEGORIES = ${JSON.stringify(categories, null, 2)} as const;

export const CURATED_CLOTHING_DESIGNS: CuratedClothingDesign[] = ${JSON.stringify(
  manifest.designs.map((d: any) => ({
    id: d.id,
    folder: d.folder,
    name: d.name,
    themeCategory: d.tags[0] || 'streetwear',
    tags: d.tags,
    description: d.description || '',
    artworks: (d.artworks || []).map((a: any) => ({
      id: a.id,
      name: a.name,
      fileName: a.fileName,
      suggestedPlacement: a.suggestedPlacement,
      colorHint: a.colorHint,
      previewUrl: a.previewUrl,
      studioPreviewUrl: a.studioPreviewUrl,
    })),
    defaultArtworkId: d.defaultArtworkId,
    previewUrl: d.previewUrl,
    studioPreviewUrl: d.studioPreviewUrl,
  })),
  null,
  2
)};
`;

fs.writeFileSync(outputPath, tsCode, 'utf8');
console.log(`Generated ${outputPath} with ${manifest.designs.length} designs.`);
